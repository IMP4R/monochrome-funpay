import ast,json,os,re
from urllib.request import Request,urlopen
SYSTEM='''Ты senior Python engineer платформы плагинов. Не используй Telegram/Cardinal. Не вставляй секреты. Следуй формату буквально. Исправляй первопричину, а не симптомы. Не удаляй и не ослабляй тесты ради зеленого результата.'''
SDK='''plugin.py must export class Plugin with class attributes slug,title,version and methods: health(self,ctx)->dict; score(self,item:dict)->dict; async handle(self,event:dict,ctx)->dict. Standard library only. score and handle never raise on malformed input. tests/test_plugin.py uses unittest and from plugin import Plugin, contains at least five meaningful tests, and calls async handle with asyncio.run(...). No network, subprocess, eval, exec, dynamic imports, secrets, or external files.'''
FORBIDDEN_IMPORTS={'socket','requests','httpx','aiohttp','urllib','http','subprocess','ftplib','telnetlib'}
FORBIDDEN_CALLS={'eval','exec','compile','__import__'}

def model(messages,temperature=0.1,max_tokens=3000):
 key=os.environ.get('GEMINI_RELAY_KEY') or os.environ['POOLSIDE_API_KEY'];base=os.getenv('GEMINI_BASE_URL') or os.getenv('POOLSIDE_BASE_URL','https://inference.poolside.ai/v1');base=base.rstrip('/');mid=os.getenv('GEMINI_PRIMARY_MODEL') or os.getenv('POOLSIDE_MODEL','poolside/laguna-s-2.1')
 body=json.dumps({'model':mid,'messages':messages,'temperature':temperature,'max_tokens':max_tokens}).encode()
 req=Request(base+'/chat/completions',data=body,headers={'Authorization':'Bearer '+key,'Content-Type':'application/json'})
 with urlopen(req,timeout=150) as r:return json.loads(r.read())['choices'][0]['message']['content']

def one_json(text):
 text=text.strip();dec=json.JSONDecoder()
 for m in re.finditer(r'\{',text):
  try:
   obj,_=dec.raw_decode(text[m.start():])
   if isinstance(obj,dict):return obj
  except Exception:pass
 raise ValueError('model returned no JSON')

def validate_source(text,kind='plugin'):
 tree=ast.parse(text)
 for node in ast.walk(tree):
  if isinstance(node,(ast.Import,ast.ImportFrom)):
   names=[x.name for x in node.names] if isinstance(node,ast.Import) else [node.module or '']
   for name in names:
    root=name.split('.')[0]
    if root in FORBIDDEN_IMPORTS:raise ValueError(f'forbidden import in {kind}: {root}')
  if isinstance(node,ast.Call):
   if isinstance(node.func,ast.Name) and node.func.id in FORBIDDEN_CALLS:raise ValueError(f'forbidden call in {kind}: {node.func.id}')
   if isinstance(node.func,ast.Attribute) and isinstance(node.func.value,ast.Name) and (node.func.value.id,node.func.attr) in {('os','system'),('os','popen')}:
    raise ValueError(f'forbidden call in {kind}: {node.func.value.id}.{node.func.attr}')
 return tree

def code_only(text,kind='plugin'):
 text=text.strip();m=re.search(r'```(?:python)?\s*(.*?)```',text,re.I|re.S)
 if m:text=m.group(1).strip()
 starts=[p for p in (text.find('from '),text.find('import '),text.find('class ')) if p>=0]
 if starts and min(starts)>0:text=text[min(starts):]
 validate_source(text,kind);return text.rstrip()+'\n'

def test_count(source):return len(re.findall(r'^\s*def\s+test_[A-Za-z0-9_]+\s*\(',source,re.M))

def build_plugin(goal,knowledge=''):
 context=f'GOAL:\n{goal}\n\nKNOWLEDGE:\n{knowledge[-8000:]}\n\nSDK:\n{SDK}'
 plan_raw=model([{'role':'system','content':SYSTEM},{'role':'user','content':context+'\nReturn ONLY compact JSON: {"slug":"snake_case","title":"...","description":"...","permissions":["..."]}. No files.'}],0.0,400)
 try:plan=one_json(plan_raw)
 except Exception:plan={}
 slug=re.sub(r'[^a-z0-9_]+','_',str(plan.get('slug') or goal[:50]).lower()).strip('_')[:60] or 'generated_plugin'
 title=str(plan.get('title') or slug.replace('_',' ').title())[:120];description=str(plan.get('description') or goal[:240]);permissions=plan.get('permissions') if isinstance(plan.get('permissions'),list) else []
 plugin_raw=model([{'role':'system','content':SYSTEM},{'role':'user','content':context+f'\nThe slug MUST be {slug}. Return ONLY complete plugin.py Python source. No markdown.'}],0.05,3200)
 plugin=code_only(plugin_raw,'plugin')
 tests_raw=model([{'role':'system','content':SYSTEM},{'role':'user','content':context+'\nHere is plugin.py:\n'+plugin+'\nReturn ONLY complete tests/test_plugin.py source with at least 5 meaningful unittest tests. Import Plugin and use asyncio.run for async handle. No markdown.'}],0.05,3200)
 tests=code_only(tests_raw,'tests')
 if 'from plugin import Plugin' not in tests:raise ValueError('tests must import Plugin')
 if test_count(tests)<5:raise ValueError('at least five tests required')
 manifest=json.dumps({'slug':slug,'title':title,'version':'0.1.0','entry':'plugin:Plugin','permissions':permissions},ensure_ascii=False,indent=2)
 readme=f'# {title}\n\n{description}\n\n## Goal\n\n{goal}\n\nGenerated by the agent pipeline and activated only after sandboxed tests pass.\n'
 return {'slug':slug,'title':title,'description':description,'files':{'manifest.json':manifest,'plugin.py':plugin,'tests/test_plugin.py':tests,'README.md':readme}}, {'plan':plan_raw,'plugin_chars':len(plugin),'test_chars':len(tests)}

def repair_plugin(goal,knowledge,spec,failure,attempt):
 old_plugin=spec['files']['plugin.py'];old_tests=spec['files']['tests/test_plugin.py'];old_count=test_count(old_tests)
 base=f'''GOAL:\n{goal}\n\nSDK:\n{SDK}\n\nSANDBOX FAILURE (attempt {attempt}):\n{failure[-12000:]}\n\nCURRENT plugin.py:\n{old_plugin[-16000:]}'''
 plugin_raw=model([{'role':'system','content':SYSTEM},{'role':'user','content':base+'\nDiagnose the root cause and return ONLY the complete corrected plugin.py. Preserve all correct behavior. No markdown.'}],0.0,3600)
 plugin=code_only(plugin_raw,'plugin repair')
 tests_prompt=f'''GOAL:\n{goal}\n\nSDK:\n{SDK}\n\nFAILURE:\n{failure[-10000:]}\n\nCORRECTED plugin.py:\n{plugin[-16000:]}\n\nCURRENT tests/test_plugin.py:\n{old_tests[-16000:]}\nReturn ONLY the complete corrected tests/test_plugin.py. Keep every meaningful behavior check, do not reduce the number of test methods ({old_count}), import Plugin, and use asyncio.run for async handle. No markdown.'''
 tests_raw=model([{'role':'system','content':SYSTEM},{'role':'user','content':tests_prompt}],0.0,3600)
 tests=code_only(tests_raw,'test repair');new_count=test_count(tests)
 if 'from plugin import Plugin' not in tests:raise ValueError('repaired tests must import Plugin')
 if new_count<max(5,old_count):raise ValueError(f'repair weakened tests: {old_count} -> {new_count}')
 updated={**spec,'files':dict(spec['files'])};updated['files']['plugin.py']=plugin;updated['files']['tests/test_plugin.py']=tests
 return updated,{'attempt':attempt,'plugin_changed':plugin!=old_plugin,'tests_changed':tests!=old_tests,'tests_before':old_count,'tests_after':new_count,'plugin_chars':len(plugin),'test_chars':len(tests)}
